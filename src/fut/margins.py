def margin_per_lot(code: str, price) -> float | None:
    """按加权现价估算的一手保证金（元）；表外品种返回 None。"""
    hit = MARGINS.get((code or "").upper())
    if not hit or price is None:
        return None
    try:
        p = float(price)
    except (TypeError, ValueError):
        return None
    if p <= 0:
        return None
    mult, rate = hit
    return round(p * mult * rate)
